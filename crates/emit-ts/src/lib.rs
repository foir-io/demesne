#[must_use]
pub fn ts_json(v: &Value, indent: bool) -> String {
    if indent { json::marshal_indent_opts(v, "", "  ", false) } else { json::marshal_opts(v, false) }
}

#[must_use]
pub fn ts_str(s: &str) -> String {
    ts_json(&Value::str(s), false)
}

struct Decl {
    name: &'static str,
    ty: &'static str,
    lit: String,
}

/// Emits the TypeScript projection module `@foir/demesne` consumes.
///
/// # Errors
///
/// The claims projection cannot be built. Surfaces a spec cannot produce are left out.
pub fn emit_ts(s: &Spec) -> Result<String, Error> {
    let decls: Vec<Decl> = projections::all(s)?
        .into_iter()
        .map(|p| {
            let (name, ty) = match p.shape {
                Shape::Claims => ("claims", "Claims"),
                Shape::AppSurface => ("appSurface", "AppObjectSurface[]"),
                Shape::Pdp => ("pdp", "Record<string, Pdp>"),
                Shape::HoldsResolver => ("holdsResolver", "HoldsResolver"),
                Shape::RoleAssignment => ("roleAssignment", "RoleAssignmentSurface"),
                Shape::Grants => ("grants", "Record<string, GrantSurface>"),
                Shape::ResourceAccess => ("resourceAccess", "Record<string, ResourceAccessSurface>"),
            };
            Decl { name, ty, lit: ts_json(&p.value, true) }
        })
        .collect();
    Ok(render_module(&decls))
}

fn render_module(decls: &[Decl]) -> String {
    let mut types = BTreeSet::new();
    for d in decls {
        let mut t = d.ty.strip_suffix("[]").unwrap_or(d.ty);
        if let Some(rest) = t.strip_prefix("Record<string, ") {
            t = rest.strip_suffix('>').unwrap_or(rest);
        }
        types.insert(t);
    }
    let mut b = String::from("// Code generated by Demesne. DO NOT EDIT.\n\n");
    writeln!(b, "import type {{ {} }} from \"@foir/demesne\";", types.into_iter().collect::<Vec<_>>().join(", ")).expect("fmt::Write for String never fails");
    for d in decls {
        write!(b, "\nexport const {}: {} = {};\n", d.name, d.ty, d.lit).expect("fmt::Write for String never fails");
    }
    b
}

/// Renders the claims contract as an exported TypeScript `string[]` named `var_name`.
///
/// # Errors
///
/// The topology has no single root, or a level is unreachable from it.
pub fn render_claims_contract_ts(s: &Spec, var_name: &str) -> Result<String, Error> {
    let keys = s.claims_contract()?;
    Ok(format!("// Code generated by Demesne. DO NOT EDIT.\nexport const {var_name}: string[] = {};\n", ts_json(&Value::strings(&keys), false)))
}

#[must_use]
pub fn render_pdp_ts(p: &Pdp, var_name: &str) -> String {
    let m = Value::Map(p.policy.iter().map(|(k, v)| (k.to_string(), Value::str(v.as_ref()))).collect());
    format!("// Code generated by Demesne. DO NOT EDIT.\nexport const {var_name}: Record<string, string> = {};\n", ts_json(&m, false))
}

#[must_use]
pub fn render_field_access_ts(fa: &FieldAccess) -> String {
    use demesne_gocompat::{go_export, quote};
    let tn = go_export(&fa.object);
    let pt = format!("{tn}FieldPrincipal");
    let policy = format!("{tn}FieldPolicy");
    let list = |toks: &[String]| toks.iter().map(|t| quote(t)).collect::<Vec<_>>().join(", ");
    let mut b = String::new();
    write!(b, "// Code generated by Demesne field-access (object {}). DO NOT EDIT.\n\n", quote(&fa.object)).expect("fmt::Write for String never fails");
    let lits: Vec<String> = fa.principals.iter().map(|p| quote(p)).collect();
    write!(b, "export type {pt} = {};\n\n", lits.join(" | ")).expect("fmt::Write for String never fails");
    writeln!(b, "export class {policy} {{").expect("fmt::Write for String never fails");
    writeln!(b, "  private read = new Map<string, {pt}[]>();").expect("fmt::Write for String never fails");
    write!(b, "  private write = new Map<string, {pt}[]>();\n\n").expect("fmt::Write for String never fails");
    b.push_str("  constructor() {\n");
    for r in &fa.rules {
        if !r.read.is_empty() {
            writeln!(b, "    this.read.set({}, [{}]);", quote(&r.field), list(&r.read)).expect("fmt::Write for String never fails");
        }
        if !r.write.is_empty() {
            writeln!(b, "    this.write.set({}, [{}]);", quote(&r.field), list(&r.write)).expect("fmt::Write for String never fails");
        }
    }
    b.push_str("  }\n\n");
    writeln!(b, "  setRead(field: string, ...who: {pt}[]): void {{ this.read.set(field, who); }}").expect("fmt::Write for String never fails");
    write!(b, "  setWrite(field: string, ...who: {pt}[]): void {{ this.write.set(field, who); }}\n\n").expect("fmt::Write for String never fails");
    writeln!(b, "  canReadField(field: string, who: {pt}): boolean {{ return fieldAllowed(this.read, field, who); }}")
        .expect("fmt::Write for String never fails");
    writeln!(b, "  canWriteField(field: string, who: {pt}): boolean {{ return fieldAllowed(this.write, field, who); }}")
        .expect("fmt::Write for String never fails");
    b.push_str("}\n\n");
    b.push_str("function fieldAllowed<T>(m: Map<string, T[]>, field: string, who: T): boolean {\n");
    b.push_str("  const allow = m.get(field);\n");
    b.push_str("  if (allow === undefined) return true;\n");
    b.push_str("  return allow.includes(who);\n");
    b.push_str("}\n");
    b
}
