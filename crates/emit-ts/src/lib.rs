#![doc = "Emits demesne's TypeScript surface: the projection module consumed by @foir/demesne, the claims contract, PDP maps and the typed framework module."]

mod framework;
pub mod projections;

pub use framework::emit_framework_ts;

use demesne_emit_sql::Sql;
use demesne_gocompat::json::{self, Value};
use demesne_model::analysis::object_grant_edge;
use demesne_model::pdp::{FieldAccess, emit_pdp};
use demesne_model::{SpecExt, SurfaceExt};
use demesne_runtime::Pdp;
use demesne_syntax::Spec;
use std::collections::BTreeSet;

pub fn ts_json(v: &Value, indent: bool) -> String {
    if indent { json::marshal_indent_opts(v, "", "  ", false) } else { json::marshal_opts(v, false) }
}

pub fn ts_str(s: &str) -> String {
    ts_json(&Value::str(s), false)
}

struct Decl {
    name: &'static str,
    ty: &'static str,
    lit: String,
}

pub fn emit_ts(s: &Spec) -> Result<String, String> {
    let mut decls = Vec::new();
    let cl = projections::claims(s).map_err(|e| format!("EmitTS claims: {e}"))?;
    decls.push(Decl { name: "claims", ty: "Claims", lit: ts_json(&cl, true) });
    if let Ok(surf) = Sql::new(s).emit_app_surface() {
        let objs: Vec<Value> = surf.objects.iter().map(projections::app_object).collect();
        decls.push(Decl { name: "appSurface", ty: "AppObjectSurface[]", lit: ts_json(&Value::Array(objs), true) });
    }
    if let Ok(pdps) = emit_pdp(s)
        && !pdps.is_empty()
    {
        let m = Value::Map(pdps.iter().map(|(k, p)| (k.clone(), projections::pdp(p))).collect());
        decls.push(Decl { name: "pdp", ty: "Record<string, Pdp>", lit: ts_json(&m, true) });
    }
    if !s.role_stores.is_empty() {
        let hr = s.holds_resolver("").map_err(|e| format!("EmitTS holdsResolver: {e}"))?;
        decls.push(Decl { name: "holdsResolver", ty: "HoldsResolver", lit: ts_json(&projections::holds(&hr), true) });
        let ra = s.role_assignment_surface("").map_err(|e| format!("EmitTS roleAssignment: {e}"))?;
        decls.push(Decl { name: "roleAssignment", ty: "RoleAssignmentSurface", lit: ts_json(&projections::role_assign(&ra), true) });
    }
    if !s.grants.is_empty() {
        let mut m = Vec::new();
        for g in &s.grants {
            if g.claim_key.is_some() {
                continue;
            }
            let gs = s.grant_surface(&g.name).map_err(|e| format!("EmitTS grant {}: {e}", demesne_gocompat::quote(&g.name)))?;
            m.retain(|(k, _): &(String, Value)| k != &g.name);
            m.push((g.name.clone(), projections::grant(&gs)));
        }
        decls.push(Decl { name: "grants", ty: "Record<string, GrantSurface>", lit: ts_json(&Value::Map(m), true) });
    }
    let mut ram: Vec<(String, Value)> = Vec::new();
    for o in &s.objects {
        if object_grant_edge(o).is_none() {
            continue;
        }
        let r = s
            .conditional_resource_access_surface(&o.name)
            .map_err(|e| format!("EmitTS resourceAccess {}: {e}", demesne_gocompat::quote(&o.name)))?;
        ram.retain(|(k, _)| k != &o.name);
        ram.push((o.name.clone(), projections::res_access(&r)));
    }
    if !ram.is_empty() {
        decls.push(Decl { name: "resourceAccess", ty: "Record<string, ResourceAccessSurface>", lit: ts_json(&Value::Map(ram), true) });
    }
    Ok(render_module(&decls))
}

fn render_module(decls: &[Decl]) -> String {
    let mut types = BTreeSet::new();
    for d in decls {
        let mut t = d.ty.strip_suffix("[]").unwrap_or(d.ty);
        if let Some(rest) = t.strip_prefix("Record<string, ") {
            t = rest.strip_suffix('>').unwrap_or(rest);
        }
        types.insert(t);
    }
    let mut b = String::from("// Code generated by Demesne. DO NOT EDIT.\n\n");
    b.push_str(&format!("import type {{ {} }} from \"@foir/demesne\";\n", types.into_iter().collect::<Vec<_>>().join(", ")));
    for d in decls {
        b.push_str(&format!("\nexport const {}: {} = {};\n", d.name, d.ty, d.lit));
    }
    b
}

pub fn render_claims_contract_ts(s: &Spec, var_name: &str) -> Result<String, String> {
    let keys = s.claims_contract()?;
    Ok(format!(
        "// Code generated by Demesne. DO NOT EDIT.\nexport const {var_name}: string[] = {};\n",
        ts_json(&Value::strings(&keys), false)
    ))
}

pub fn render_pdp_ts(p: &Pdp, var_name: &str) -> String {
    let m = Value::Map(p.policy.iter().map(|(k, v)| (k.clone(), Value::str(v))).collect());
    format!("// Code generated by Demesne. DO NOT EDIT.\nexport const {var_name}: Record<string, string> = {};\n", ts_json(&m, false))
}

pub fn render_field_access_ts(fa: &FieldAccess) -> String {
    use demesne_gocompat::{go_export, quote};
    let tn = go_export(&fa.object);
    let pt = format!("{tn}FieldPrincipal");
    let policy = format!("{tn}FieldPolicy");
    let list = |toks: &[String]| toks.iter().map(|t| quote(t)).collect::<Vec<_>>().join(", ");
    let mut b = String::new();
    b.push_str(&format!("// Code generated by Demesne field-access (object {}). DO NOT EDIT.\n\n", quote(&fa.object)));
    let lits: Vec<String> = fa.principals.iter().map(|p| quote(p)).collect();
    b.push_str(&format!("export type {pt} = {};\n\n", lits.join(" | ")));
    b.push_str(&format!("export class {policy} {{\n"));
    b.push_str(&format!("  private read = new Map<string, {pt}[]>();\n"));
    b.push_str(&format!("  private write = new Map<string, {pt}[]>();\n\n"));
    b.push_str("  constructor() {\n");
    for r in &fa.rules {
        if !r.read.is_empty() {
            b.push_str(&format!("    this.read.set({}, [{}]);\n", quote(&r.field), list(&r.read)));
        }
        if !r.write.is_empty() {
            b.push_str(&format!("    this.write.set({}, [{}]);\n", quote(&r.field), list(&r.write)));
        }
    }
    b.push_str("  }\n\n");
    b.push_str(&format!("  setRead(field: string, ...who: {pt}[]): void {{ this.read.set(field, who); }}\n"));
    b.push_str(&format!("  setWrite(field: string, ...who: {pt}[]): void {{ this.write.set(field, who); }}\n\n"));
    b.push_str(&format!("  canReadField(field: string, who: {pt}): boolean {{ return fieldAllowed(this.read, field, who); }}\n"));
    b.push_str(&format!("  canWriteField(field: string, who: {pt}): boolean {{ return fieldAllowed(this.write, field, who); }}\n"));
    b.push_str("}\n\n");
    b.push_str("function fieldAllowed<T>(m: Map<string, T[]>, field: string, who: T): boolean {\n");
    b.push_str("  const allow = m.get(field);\n");
    b.push_str("  if (allow === undefined) return true;\n");
    b.push_str("  return allow.includes(who);\n");
    b.push_str("}\n");
    b
}
