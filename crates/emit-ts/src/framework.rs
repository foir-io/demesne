use crate::{projections, ts_json, ts_str};
use demesne_emit_go::{check_accessor_collisions, orphan_pdp_verbs, role_tier_fields, vocab_caps_tree};
use demesne_emit_sql::Sql;
use demesne_gocompat::json::Value;
use demesne_gocompat::{go_export, unexport};
use demesne_model::{SpecExt, SurfaceExt};
use demesne_runtime::{AppObjectSurface, HoldsResolver};
use demesne_syntax::*;
use std::collections::HashSet;

type R<T> = Result<T, String>;

struct Check {
    object: String,
    verb: String,
    method: String,
}

#[derive(Default)]
struct Needs {
    compose: bool,
    resolve: bool,
    resolve_roles: bool,
    eff: bool,
    eff_roles: bool,
    holds: bool,
    ra: bool,
}

struct Gen<'a> {
    s: &'a Spec,
    b: String,
    checks: Vec<Check>,
    pdp_checks: Vec<Check>,
    need: Needs,
}

pub fn emit_framework_ts(s: &Spec) -> R<String> {
    let contract = s.claims_contract()?;
    let surf = Sql::new(s).emit_app_surface()?;
    check_accessor_collisions(s, &surf.objects)?;
    let mut g = Gen { s, b: String::new(), checks: Vec::new(), pdp_checks: Vec::new(), need: Needs::default() };
    g.claims(&contract);
    g.querier();
    let skipped: Vec<&Object> = s.objects.iter().filter(|o| !o.point_checkable()).collect();
    g.banner(&skipped);
    g.pdp_banner(&orphan_pdp_verbs(s));
    for o in &surf.objects {
        if let Some(obj) = s.object_by_name(&o.object) {
            g.object(o, obj);
        }
    }
    let mut emitted_caps = HashSet::new();
    let mut emitted_roles = HashSet::new();
    for rs in &s.role_stores {
        let suffix = if s.role_stores.len() > 1 { go_export(&rs.name) } else { String::new() };
        g.holds(rs, &suffix)?;
        let v = s.rolestore_vocab(rs)?;
        if emitted_caps.insert(v.name.clone()) {
            g.vocab_caps(v, &suffix)?;
        }
        g.holds_roles(rs, &suffix)?;
        if emitted_roles.insert(v.name.clone()) {
            g.role_tiers(v, &suffix)?;
        }
    }
    g.check_func();
    g.check_handler();
    Ok(g.assemble())
}

fn scope_expr(suffix: &str, r: &HoldsResolver) -> String {
    const CELL: &str = "(c) => (row[c] == null ? \"\" : String(row[c]))";
    let sel = r.selected_scope_cols().len();
    if sel == r.scope_cols.len() {
        return format!("holdsResolver{suffix}.scopeCols.map({CELL})");
    }
    format!("holdsResolver{suffix}.scopeCols.slice(0, {sel}).map({CELL})")
}

fn capability_gate_msg(object: &str, verb: &str) -> String {
    format!(
        "{object}.{verb} is a capability (@pdp) verb with no row-level check — resolve held permissions and call can{}(held) on the {} object",
        go_export(verb),
        unexport(object)
    )
}

impl Gen<'_> {
    fn w(&mut self, s: &str) {
        self.b.push_str(s);
    }

    fn assemble(&self) -> String {
        let mut head = String::from("// Code generated by Demesne. DO NOT EDIT.\n\n");
        let mut values = vec!["Decision", "mintClaimsValuesWithExtra"];
        if self.need.compose {
            values.push("composeCan");
        }
        if self.need.resolve {
            values.push("resolve");
        }
        if self.need.resolve_roles {
            values.push("resolveRoles");
        }
        values.sort();
        head.push_str(&format!("import {{ {} }} from \"@foir/demesne\";\n", values.join(", ")));
        let mut types = Vec::new();
        if self.need.eff {
            types.push("EffectivePerms");
        }
        if self.need.eff_roles {
            types.push("EffectiveRoles");
        }
        if self.need.holds {
            types.push("HoldsResolver");
        }
        if self.need.ra {
            types.push("RoleAssignment");
        }
        if !types.is_empty() {
            types.sort();
            head.push_str(&format!("import type {{ {} }} from \"@foir/demesne\";\n", types.join(", ")));
        }
        head.push_str("\nexport { Decision };\n\n");
        head + &self.b
    }

    fn claims(&mut self, contract: &[String]) {
        let session = self.s.session();
        self.w(&format!("export const claimsContract: string[] = {};\n\n", ts_json(&Value::strings(contract), false)));
        self.w("export interface Claims {\n");
        for k in contract {
            self.w(&format!("  {}?: string;\n", unexport(k)));
        }
        self.w("  extra?: Record<string, string>;\n}\n\n");
        self.w("export function mint(c: Claims): string {\n  const values: Record<string, string> = {};\n");
        for k in contract {
            let f = unexport(k);
            self.w(&format!("  if (c.{f} !== undefined && c.{f} !== \"\") values[{}] = c.{f};\n", ts_str(k)));
        }
        self.w("  return mintClaimsValuesWithExtra(claimsContract, values, c.extra);\n}\n\n");
        self.w(&format!("export const connectionRole = {};\n", ts_str(&session.role)));
        self.w(&format!("export const claimsGUC = {};\n\n", ts_str(&session.setting)));
        self.w("export function setRoleSQL(local: boolean): string {\n  return (local ? \"SET LOCAL ROLE \" : \"SET ROLE \") + connectionRole;\n}\n\nexport function claimsSetSQL(local: boolean): string {\n  return \"SELECT set_config('\" + claimsGUC + \"', $1, \" + (local ? \"true\" : \"false\") + \")\";\n}\n\nexport function sessionSetupSQL(local: boolean): [string, string] {\n  return [setRoleSQL(local), claimsSetSQL(local)];\n}\n\n");
    }

    fn querier(&mut self) {
        self.w("export interface Querier {\n  query(text: string, params: unknown[]): Promise<{ rows: any[] }>;\n}\n\n");
    }

    fn banner(&mut self, skipped: &[&Object]) {
        if skipped.is_empty() {
            return;
        }
        self.w("// These objects declare a composite primary key — no single-column row identity, so no\n");
        self.w("// can / listResources / checkMany is generated for them. Reach such rows via your own\n");
        self.w("// predicate or a related object:\n");
        for o in skipped {
            self.w(&format!("//   - {} (table {}, pk {})\n", o.name, o.table, o.pk_cols.join(", ")));
        }
        self.w("\n");
    }

    fn pdp_banner(&mut self, orphan: &[String]) {
        if orphan.is_empty() {
            return;
        }
        self.w("// These @pdp verbs need a permission no rolestore vocabulary covers, so no holds\n");
        self.w("// resolver is generated for them — resolve their held input yourself, or add a rolestore\n");
        self.w("// for the permission's vocabulary:\n");
        for v in orphan {
            self.w(&format!("//   - {v}\n"));
        }
        self.w("\n");
    }

    fn object(&mut self, o: &AppObjectSurface, obj: &Object) {
        let name = unexport(&o.object);
        self.w(&format!("export const {name} = {{\n"));
        let mut parts: Vec<String> = Vec::new();
        for pm in &obj.perms {
            let method = format!("can{}", go_export(&pm.verb));
            if pm.has_layer("pdp") {
                self.need.eff = true;
                parts.push(pdp_can(&method, pm));
                self.pdp_checks.push(Check { object: o.object.clone(), verb: pm.verb.clone(), method: String::new() });
                continue;
            }
            let sql = if pm.maps() == "select" {
                o.check_sql()
            } else if pm.maps() == "update" {
                if o.edit_check_sql.is_empty() {
                    continue;
                }
                o.edit_check_sql.clone()
            } else if pm.has_layer("check") {
                let sql = o.check_verb_sql(&pm.verb);
                if sql.is_empty() {
                    continue;
                }
                sql.to_string()
            } else {
                continue;
            };
            self.need.compose = true;
            parts.push(row_can(&method, &sql));
            self.checks.push(Check { object: o.object.clone(), verb: pm.verb.clone(), method: format!("{name}.{method}") });
        }
        let list_sql = if o.flat_list_fn.is_empty() { o.list_resources_sql() } else { o.list_resources_fast_sql() };
        parts.push(format!(
            "  async listResources(q: Querier, after: string | null, limit: number): Promise<string[]> {{\n    const {{ rows }} = await q.query({}, [after, limit]);\n    return rows.map((r) => r[{}] as string);\n  }},\n",
            ts_str(&list_sql),
            ts_str(&o.pk)
        ));
        parts.push(format!(
            "  async checkMany(q: Querier, ids: string[]): Promise<string[]> {{\n    const {{ rows }} = await q.query({}, [ids]);\n    return rows.map((r) => r[{}] as string);\n  }},\n",
            ts_str(&o.check_many_sql()),
            ts_str(&o.pk)
        ));
        self.w(&parts.join("\n"));
        self.w("};\n\n");
    }

    fn holds(&mut self, rs: &RoleStore, suffix: &str) -> R<()> {
        let r = self.s.holds_resolver(&rs.name)?;
        self.need.resolve = true;
        self.need.eff = true;
        self.need.holds = true;
        self.need.ra = true;
        self.w(&format!("export const holdsResolver{suffix}: HoldsResolver = {};\n\n", ts_json(&projections::holds(&r), true)));
        self.w(&format!("export const assignmentsSQL{suffix} = {};\n\n", ts_str(&r.assignments_sql())));
        self.w(&format!(
            "export function resolveHeld{suffix}(assignments: RoleAssignment[], scope: string[]): EffectivePerms {{\n  return resolve(holdsResolver{suffix}, assignments, scope);\n}}\n\n"
        ));
        self.w(&format!(
            "export async function holds{suffix}(q: Querier, principalId: string, scope: string[]): Promise<EffectivePerms> {{\n"
        ));
        self.assignment_rows(suffix, &r);
        self.w(&format!("  return resolveHeld{suffix}(assignments, scope);\n}}\n\n"));
        Ok(())
    }

    fn assignment_rows(&mut self, suffix: &str, r: &HoldsResolver) {
        self.w(&format!("  const {{ rows }} = await q.query(assignmentsSQL{suffix}, [principalId]);\n"));
        self.w("  const assignments: RoleAssignment[] = rows.map((row) => ({\n");
        self.w(&format!("    scope: {},\n", scope_expr(suffix, r)));
        self.w(&format!("    roleKey: String(row[holdsResolver{suffix}.keyCol]),\n"));
        self.w(&format!(
            "    permissions: holdsResolver{suffix}.permsCol !== \"\" ? (row[holdsResolver{suffix}.permsCol] as string[]) : [],\n"
        ));
        self.w("  }));\n");
    }

    fn check_func(&mut self) {
        self.w("export async function check(q: Querier, object: string, verb: string, id: string): Promise<Decision> {\n");
        self.w("  switch (object + \".\" + verb) {\n");
        let checks = std::mem::take(&mut self.checks);
        for c in &checks {
            self.w(&format!("    case {}:\n      return {}(q, id);\n", ts_str(&format!("{}.{}", c.object, c.verb)), c.method));
        }
        let pdp = std::mem::take(&mut self.pdp_checks);
        for c in &pdp {
            self.w(&format!(
                "    case {}:\n      throw new Error({});\n",
                ts_str(&format!("{}.{}", c.object, c.verb)),
                ts_str(&capability_gate_msg(&c.object, &c.verb))
            ));
        }
        self.w("    default:\n      return Decision.NotGoverned;\n  }\n}\n\n");
    }

    fn vocab_caps(&mut self, v: &Vocabulary, suffix: &str) -> R<()> {
        let (domains, skipped) = vocab_caps_tree(&v.permissions)?;
        if !skipped.is_empty() {
            self.w("// These vocabulary permissions are parameterized (a '*' model segment) and have no static\n");
            self.w("// caps field — check them with held.holds(\"<domain>:<verb>:<model>\") directly:\n");
            for p in &skipped {
                self.w(&format!("//   - {p}\n"));
            }
            self.w("\n");
        }
        if domains.is_empty() {
            return Ok(());
        }
        self.need.eff = true;
        self.w(&format!("export function caps{suffix}(held: EffectivePerms) {{\n  return {{\n"));
        for d in &domains {
            self.w(&format!("    {}: {{\n", unexport(&d.exp)));
            for f in &d.fields {
                self.w(&format!("      {}: held.holds({}),\n", unexport(&f.exp), ts_str(&f.perm)));
            }
            self.w("    },\n");
        }
        self.w("  };\n}\n\n");
        Ok(())
    }

    fn holds_roles(&mut self, rs: &RoleStore, suffix: &str) -> R<()> {
        let r = self.s.holds_resolver(&rs.name)?;
        self.need.resolve_roles = true;
        self.need.eff_roles = true;
        self.need.ra = true;
        self.w(&format!(
            "export function resolveHeldRoles{suffix}(assignments: RoleAssignment[], scope: string[]): EffectiveRoles {{\n  return resolveRoles(assignments, scope);\n}}\n\n"
        ));
        self.w(&format!(
            "export async function holdsRoles{suffix}(q: Querier, principalId: string, scope: string[]): Promise<EffectiveRoles> {{\n"
        ));
        self.assignment_rows(suffix, &r);
        self.w(&format!("  return resolveHeldRoles{suffix}(assignments, scope);\n}}\n\n"));
        Ok(())
    }

    fn role_tiers(&mut self, v: &Vocabulary, suffix: &str) -> R<()> {
        let fields = role_tier_fields(self.s, v)?;
        if fields.is_empty() {
            return Ok(());
        }
        self.need.eff_roles = true;
        self.w(&format!("export function roleTiers{suffix}(held: EffectiveRoles) {{\n  return {{\n"));
        for (exp, key) in &fields {
            self.w(&format!("    {}: held.holds({}),\n", unexport(exp), ts_str(key)));
        }
        self.w("  };\n}\n\n");
        Ok(())
    }

    fn check_handler(&mut self) {
        self.w("export function checkHandler(q: Querier): (req: Request) => Promise<Response> {\n  return async (req: Request): Promise<Response> => {\n    const url = new URL(req.url);\n    try {\n      const d = await check(\n        q,\n        url.searchParams.get(\"object\") ?? \"\",\n        url.searchParams.get(\"verb\") ?? \"\",\n        url.searchParams.get(\"id\") ?? \"\",\n      );\n      return new Response(JSON.stringify({ decision: d }), {\n        headers: { \"Content-Type\": \"application/json\" },\n      });\n    } catch (e) {\n      return new Response((e as Error).message, { status: 500 });\n    }\n  };\n}\n");
    }
}

fn row_can(method: &str, sql: &str) -> String {
    format!(
        "  async {method}(q: Querier, id: string): Promise<Decision> {{\n    const {{ rows }} = await q.query({}, [id]);\n    return composeCan(true, Boolean(rows[0]?.exists), Decision.NotGoverned);\n  }},\n",
        ts_str(sql)
    )
}

fn pdp_can(method: &str, pm: &Perm) -> String {
    let mut b = format!("  {method}(held: EffectivePerms): Decision {{\n");
    for t in pm.tree.leaves() {
        if !t.ident().is_empty() {
            b.push_str(&format!("    if (!held.holds({})) return Decision.Deny;\n", ts_str(t.ident())));
        } else if t.builtin() == "holds" && !t.holds_perm().is_empty() {
            b.push_str(&format!("    if (!held.holds({})) return Decision.Deny;\n", ts_str(t.holds_perm())));
        }
    }
    b.push_str("    return Decision.Allow;\n  },\n");
    b
}
