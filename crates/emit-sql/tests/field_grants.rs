use demesne_emit_sql::render_field_grants;
use demesne_model::pdp::{FieldAccess, FieldAccessRule};

fn rule(field: &str, read: &[&str], write: &[&str], column: &str) -> FieldAccessRule {
    FieldAccessRule {
        field: field.into(),
        read: read.iter().map(|r| (*r).to_string()).collect(),
        write: write.iter().map(|w| (*w).to_string()).collect(),
        column: column.into(),
    }
}

#[test]
fn field_grants_grant_each_mapped_column_by_column_verb_and_role() {
    let fa = FieldAccess {
        object: "profile".into(),
        principals: vec!["admin".into(), "self".into()],
        rules: vec![rule("ssn", &["admin"], &["admin"], "ssn"), rule("nickname", &["self", "public"], &[], "nick"), rule("score", &["admin"], &["admin"], "")],
    };
    assert_eq!(
        render_field_grants(&fa, "public.profiles"),
        "-- Code generated by Demesne field-access (object \"profile\"). DO NOT EDIT.
GRANT SELECT (nick) ON public.profiles TO public;
GRANT SELECT (nick) ON public.profiles TO self;
GRANT SELECT (ssn) ON public.profiles TO admin;
GRANT UPDATE (ssn) ON public.profiles TO admin;
"
    );
}

#[test]
fn rules_without_a_column_grant_nothing() {
    let fa = FieldAccess { object: "profile".into(), principals: vec!["admin".into()], rules: vec![rule("score", &["admin"], &["admin"], "")] };
    assert_eq!(render_field_grants(&fa, "public.profiles"), "");
}
