use demesne_emit_sql::{Sql, definers_sql};
use demesne_syntax::Spec;
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn load(name: &str) -> Spec {
    let src = std::fs::read_to_string(root().join("examples").join(name)).expect("the example exists");
    let s = demesne_syntax::parse(&src).expect("the example parses");
    demesne_emit_sql::validate(&s).expect("the example validates");
    s
}

fn roundtrip_ddl(s: &Spec, src: &str) -> String {
    let sql = Sql::new(s);
    let defs = sql.emit_definers().expect("the example's definers compile");
    let rls = sql.emit_rls().expect("the example's policies compile");
    assert_eq!(rls.unsupported, [] as [std::string::String; 0]);
    let mut b = format!("-- Code generated by Demesne from examples/{src}. DO NOT EDIT.\n\n");
    b.push_str(&definers_sql(&defs));
    b.push('\n');
    b.push_str(&rls.enablement_sql());
    b.push('\n');
    b.push_str(&rls.policy_sql("authenticated"));
    if !b.ends_with('\n') {
        b.push('\n');
    }
    b
}

#[test]
fn rust_regenerates_every_committed_golden() {
    let example = load("example.demesne");
    let supabase = load("supabase.demesne");
    let roundtrip = load("roundtrip.demesne");
    let require = load("require.demesne");
    let mut hook = Sql::new(&supabase).emit_supabase_profile().unwrap();
    if !hook.ends_with('\n') {
        hook.push('\n');
    }
    let dir = "ts/packages/example-app/generated";
    let goldens: Vec<(String, String)> = vec![
        (format!("{dir}/projection.ts"), demesne_emit_ts::emit_ts(&roundtrip).unwrap()),
        (format!("{dir}/policies.sql"), roundtrip_ddl(&roundtrip, "roundtrip.demesne")),
        (format!("{dir}/supabase/projection.ts"), demesne_emit_ts::emit_ts(&supabase).unwrap()),
        (format!("{dir}/supabase/policies.sql"), roundtrip_ddl(&supabase, "supabase.demesne")),
        (format!("{dir}/supabase/hook.sql"), hook),
        (format!("{dir}/require/projection.ts"), demesne_emit_ts::emit_ts(&require).unwrap()),
        (format!("{dir}/require/policies.sql"), roundtrip_ddl(&require, "require.demesne")),
        (format!("{dir}/framework.ts"), demesne_emit_ts::emit_framework_ts(&roundtrip).unwrap()),
        (format!("{dir}/exampleFramework.ts"), demesne_emit_ts::emit_framework_ts(&example).unwrap()),
    ];
    let mut stale = Vec::new();
    for (path, got) in &goldens {
        if std::env::var_os("UPDATE_ORACLE").is_some() {
            std::fs::write(root().join(path), got).expect("the golden writes");
        }
        let want = std::fs::read_to_string(root().join(path)).unwrap();
        if &want != got {
            stale.push(path.as_str());
        }
    }
    assert_eq!(goldens.len(), 9);
    assert!(stale.is_empty(), "goldens differ: {stale:?}");
}
