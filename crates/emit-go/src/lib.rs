const KEYWORDS: &[&str] = &[
    "break",
    "case",
    "chan",
    "const",
    "continue",
    "default",
    "defer",
    "else",
    "fallthrough",
    "for",
    "func",
    "go",
    "goto",
    "if",
    "import",
    "interface",
    "map",
    "package",
    "range",
    "return",
    "select",
    "struct",
    "switch",
    "type",
    "var",
];

/// The name of the Go package a generated file declares.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package(String);

impl Package {
    /// Returns the package `name`.
    ///
    /// # Errors
    ///
    /// `name` is not an ASCII Go identifier, or is the blank identifier or a keyword.
    pub fn new(name: &str) -> Result<Self, Error> {
        let mut bytes = name.bytes();
        let first = bytes.next().is_some_and(|b| b.is_ascii_alphabetic() || b == b'_');
        if !first || !bytes.all(|b| b.is_ascii_alphanumeric() || b == b'_') || name == "_" || KEYWORDS.contains(&name) {
            return Err(Error::new(format!("{} is not a Go package name", quote(name))));
        }
        Ok(Package(name.to_string()))
    }
}

impl fmt::Display for Package {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

fn header(pkg: &Package) -> String {
    format!("// Code generated by Demesne. DO NOT EDIT.\n\npackage {pkg}\n")
}

fn raw(s: &str) -> String {
    format!("`{}`", s.replace('`', "` + \"`\" + `"))
}

fn decode(ty: &str, v: &Value) -> String {
    format!("demesne.MustDecode[{ty}]({})", raw(&json::marshal_indent_opts(v, "", "  ", false)))
}

/// Emits the Go projection file the Go module `github.com/foir-io/demesne/go` reads.
///
/// # Errors
///
/// The claims projection cannot be built. Surfaces a spec cannot produce are left out.
pub fn emit_go(s: &Spec, pkg: &Package) -> Result<String, Error> {
    let mut b = header(pkg);
    b.push_str("\nimport demesne \"github.com/foir-io/demesne/go\"\n");
    for p in projections::all(s)? {
        let (name, ty) = match p.shape {
            Shape::Claims => ("Claims", "demesne.Claims"),
            Shape::AppSurface => ("AppSurface", "[]demesne.AppObjectSurface"),
            Shape::Pdp => ("PDP", "map[string]demesne.PDP"),
            Shape::HoldsResolver => ("HoldsResolver", "demesne.HoldsResolver"),
            Shape::RoleAssignment => ("RoleAssignment", "demesne.RoleAssignmentSurface"),
            Shape::Grants => ("Grants", "map[string]demesne.GrantSurface"),
            Shape::ResourceAccess => ("ResourceAccess", "map[string]demesne.ResourceAccessSurface"),
        };
        write!(b, "\nvar {name} = {}\n", decode(ty, &p.value)).expect("fmt::Write for String never fails");
    }
    Ok(b)
}

fn strings<S: AsRef<str>>(xs: &[S]) -> String {
    let items: Vec<String> = xs.iter().map(|x| quote(x.as_ref())).collect();
    format!("[]string{{{}}}", items.join(", "))
}

/// Renders the claims contract as an exported Go `[]string` named `ClaimsContract`.
///
/// # Errors
///
/// The topology has no single root, or a level is unreachable from it.
pub fn render_claims_contract_go(s: &Spec, pkg: &Package) -> Result<String, Error> {
    let keys = s.claims_contract()?;
    Ok(format!("{}\nvar ClaimsContract = {}\n", header(pkg), strings(&keys)))
}

/// Renders each emit site's policy as an exported Go `map[string]string` named for its site, as `APIPolicy` for `api`.
///
/// # Errors
///
/// The spec's procedures don't form a policy, or two sites take the same Go name.
pub fn render_pdp_go(s: &Spec, pkg: &Package) -> Result<String, Error> {
    let mut b = header(pkg);
    let mut names = HashSet::new();
    for (site, p) in &emit_pdp(s)? {
        let name = format!("{}Policy", go_export(site));
        if !names.insert(name.clone()) {
            return Err(Error::new(format!("emit site {} takes the Go name {name}, which another site has", quote(site))));
        }
        write!(b, "\nvar {name} = {}\n", policy(p)).expect("fmt::Write for String never fails");
    }
    Ok(b)
}

fn policy(p: &Pdp) -> String {
    let entries: Vec<String> = p.policy.iter().map(|(k, v)| format!("{}: {}", quote(k), quote(v))).collect();
    format!("map[string]string{{{}}}", entries.join(", "))
}
