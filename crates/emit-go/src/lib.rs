/// Renders the claims contract as a Go `[]string` variable named `var_name`.
///
/// # Errors
///
/// The topology has no single root, or a level is unreachable from it.
pub fn render_claims_contract_go(s: &Spec, var_name: &str) -> Result<String, String> {
    let keys = s.claims_contract()?;
    let mut b = String::new();
    b.push_str("// Code generated by Demesne from the authorization spec. DO NOT EDIT.\n");
    b.push_str("// The JWT claims contract: every scope column (per non-virtual topology\n");
    b.push_str("// level) + every subject identity key. WithRLS / session minting must set\n");
    b.push_str("// these; no RLS predicate may reference a key outside this set (V5).\n");
    writeln!(b, "var {var_name} = []string{{").expect("fmt::Write for String never fails");
    for k in &keys {
        writeln!(b, "\t{},", quote(k)).expect("fmt::Write for String never fails");
    }
    b.push_str("}\n");
    Ok(b)
}

fn render_string_slice<S: AsRef<str>>(ss: &[S]) -> String {
    if ss.is_empty() {
        return "nil".into();
    }
    let parts: Vec<String> = ss.iter().map(|s| quote(s.as_ref())).collect();
    format!("[]string{{{}}}", parts.join(", "))
}

/// Renders the structured claims contract as a Go slice of `DemesneClaimEntry` named `var_name`.
///
/// # Errors
///
/// The topology has no single root, or a level is unreachable from it.
pub fn render_claims_contract_entries_go(s: &Spec, var_name: &str) -> Result<String, String> {
    let entries = s.claims_contract_entries()?;
    let mut b = String::new();
    b.push_str("// Code generated by Demesne from the authorization spec. DO NOT EDIT.\n");
    b.push_str("// The STRUCTURED JWT claims contract: each key + where its value comes from\n");
    b.push_str("// (a topology level's scope id and/or a subject's identity). A derived\n");
    b.push_str("// claims-builder maps a principal onto these without hand-mapping field names.\n");
    b.push_str("type DemesneClaimEntry struct {\n\tKey      string\n\tLevel    string\n\tSubjects []string\n}\n\n");
    writeln!(b, "var {var_name} = []DemesneClaimEntry{{").expect("fmt::Write for String never fails");
    for e in &entries {
        writeln!(b, "\t{{Key: {}, Level: {}, Subjects: {}}},", quote(&e.key), quote(&e.level), render_string_slice(&e.subjects))
            .expect("fmt::Write for String never fails");
    }
    b.push_str("}\n");
    Ok(b)
}

#[must_use]
pub fn render_pdp_go(p: &Pdp, var_name: &str) -> String {
    let mut b = String::new();
    writeln!(b, "// Code generated by Demesne from the {} emit-site. DO NOT EDIT.", quote(&p.emit_site)).expect("fmt::Write for String never fails");
    writeln!(b, "var {var_name} = map[string]string{{").expect("fmt::Write for String never fails");
    for (proc_, perm) in p.policy.iter() {
        writeln!(b, "\t{}: {},", quote(proc_), quote(perm)).expect("fmt::Write for String never fails");
    }
    b.push_str("}\n");
    b
}

fn fa_const(fa: &FieldAccess, token: &str) -> String {
    format!("{}Field{}", go_export(&fa.object), go_export(token))
}

fn fa_slice(fa: &FieldAccess, toks: &[String]) -> String {
    let parts: Vec<String> = toks.iter().map(|t| fa_const(fa, t)).collect();
    format!("[]{}FieldPrincipal{{{}}}", go_export(&fa.object), parts.join(", "))
}

#[must_use]
pub fn render_field_access_go(fa: &FieldAccess) -> String {
    let tn = go_export(&fa.object);
    let pt = format!("{tn}FieldPrincipal");
    let policy = format!("{tn}FieldPolicy");
    let helper = format!("{}FieldAllowed", unexport(&fa.object));
    let mut b = String::new();
    write!(b, "// Code generated by Demesne field-access (object {}). DO NOT EDIT.\n\n", quote(&fa.object)).expect("fmt::Write for String never fails");
    write!(b, "type {pt} string\n\n").expect("fmt::Write for String never fails");
    b.push_str("const (\n");
    for tok in &fa.principals {
        writeln!(b, "\t{} {pt} = {}", fa_const(fa, tok), quote(tok)).expect("fmt::Write for String never fails");
    }
    b.push_str(")\n\n");
    write!(b, "type {policy} struct {{\n\tread  map[string][]{pt}\n\twrite map[string][]{pt}\n}}\n\n").expect("fmt::Write for String never fails");
    writeln!(b, "func New{policy}() *{policy} {{").expect("fmt::Write for String never fails");
    writeln!(b, "\tp := &{policy}{{read: map[string][]{pt}{{}}, write: map[string][]{pt}{{}}}}").expect("fmt::Write for String never fails");
    for r in &fa.rules {
        if !r.read.is_empty() {
            writeln!(b, "\tp.read[{}] = {}", quote(&r.field), fa_slice(fa, &r.read)).expect("fmt::Write for String never fails");
        }
        if !r.write.is_empty() {
            writeln!(b, "\tp.write[{}] = {}", quote(&r.field), fa_slice(fa, &r.write)).expect("fmt::Write for String never fails");
        }
    }
    b.push_str("\treturn p\n}\n\n");
    writeln!(b, "func (p *{policy}) SetRead(field string, who ...{pt})  {{ p.read[field] = who }}").expect("fmt::Write for String never fails");
    write!(b, "func (p *{policy}) SetWrite(field string, who ...{pt}) {{ p.write[field] = who }}\n\n").expect("fmt::Write for String never fails");
    writeln!(b, "func (p *{policy}) CanReadField(field string, who {pt}) bool  {{ return {helper}(p.read, field, who) }}")
        .expect("fmt::Write for String never fails");
    write!(b, "func (p *{policy}) CanWriteField(field string, who {pt}) bool {{ return {helper}(p.write, field, who) }}\n\n")
        .expect("fmt::Write for String never fails");
    writeln!(b, "func {helper}(m map[string][]{pt}, field string, who {pt}) bool {{").expect("fmt::Write for String never fails");
    b.push_str("\tallow, restricted := m[field]\n\tif !restricted {\n\t\treturn true\n\t}\n");
    b.push_str("\tfor _, a := range allow {\n\t\tif a == who {\n\t\t\treturn true\n\t\t}\n\t}\n");
    b.push_str("\treturn false\n}\n");
    b
}
