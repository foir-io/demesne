use demesne_emit_go::{Package, emit_framework_go, emit_go, render_pdp_go};
use demesne_emit_ts::projections::{self, Shape};
use demesne_gocompat::json;

const SPEC: &str = include_str!("../../../testdata/go/backtick.demesne");

fn spec(src: &str) -> demesne_syntax::Spec {
    let s = demesne_syntax::parse(src).expect("the spec parses");
    demesne_emit_sql::validate(&s).expect("the spec validates");
    s
}

fn pkg() -> Package {
    Package::new("authz").expect("authz is a package name")
}

fn go_string(expr: &str) -> String {
    let mut out = String::new();
    let mut rest = expr.trim();
    while !rest.is_empty() {
        let (open, body) = rest.split_at(1);
        let close = body.find(open).expect("every literal closes");
        assert!(open == "`" || !body[..close].contains('\\'), "an escape in {rest:?}");
        out.push_str(&body[..close]);
        rest = body[close + 1..].trim_start().trim_start_matches('+').trim_start();
    }
    out
}

#[test]
fn a_package_name_is_a_plain_go_identifier() {
    for ok in ["authz", "_x", "a1", "Authz"] {
        assert!(Package::new(ok).is_ok(), "{ok}");
    }
    for bad in ["", "1a", "a-b", "_", "func", "type", "π", "a b"] {
        assert!(Package::new(bad).is_err(), "{bad:?}");
    }
}

#[test]
fn a_backtick_in_a_spec_string_survives_the_raw_literal() {
    let s = spec(SPEC);
    let out = emit_go(&s, &pkg()).expect("the projections emit");
    assert!(out.contains("` + \"`\" + `"), "{out}");
    let start = out.find("var HoldsResolver = demesne.MustDecode[demesne.HoldsResolver](").expect("the resolver is declared");
    let args = &out[start..];
    let args = &args[args.find('(').expect("a call") + 1..args.find(")\n").expect("the call ends")];
    let want = projections::all(&s).expect("the projections build").into_iter().find(|p| p.shape == Shape::HoldsResolver).expect("a resolver");
    assert_eq!(go_string(args), json::marshal_indent_opts(&want.value, "", "  ", false));
    assert!(go_string(args).contains("st`aff"));
}

#[test]
fn two_sites_sharing_a_go_name_are_refused() {
    let both = SPEC.replace("procedures api {", "procedures API {\n  docs.v1.DocService/EditDoc -> docs:write\n}\n\nprocedures api {");
    let err = render_pdp_go(&spec(&both), &pkg()).expect_err("api and API both export as APIPolicy");
    assert!(err.to_string().contains("APIPolicy"), "{err}");
    assert!(render_pdp_go(&spec(SPEC), &pkg()).expect("one site renders").contains("var APIPolicy = map[string]string{"));
}

#[test]
fn the_framework_names_the_package_it_was_given() {
    let out = emit_framework_go(&spec(SPEC), &Package::new("guard").expect("guard is a package name")).expect("the framework emits");
    assert!(out.starts_with("// Code generated by Demesne. DO NOT EDIT.\n\npackage guard\n"), "{out}");
}
