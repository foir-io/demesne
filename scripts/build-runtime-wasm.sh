#!/usr/bin/env bash
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
OUT="$ROOT/ts/packages/runtime/src/wasm"
TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"
WANT="$(grep -A2 'name = "wasm-bindgen"' "$ROOT/Cargo.lock" | sed -n 's/^version = "\(.*\)"/\1/p' | head -1)"
HAVE="$(wasm-bindgen --version 2>/dev/null | awk '{print $2}')"
if [ "$WANT" != "$HAVE" ]; then
  echo "wasm-bindgen $WANT is required (found ${HAVE:-none}): cargo install wasm-bindgen-cli --version $WANT --locked" >&2
  exit 1
fi
(cd "$ROOT" && cargo build -p demesne-runtime-wasm --target wasm32-unknown-unknown --profile wasm)
rm -rf "$OUT"
wasm-bindgen --target web --out-dir "$OUT" "$TARGET_DIR/wasm32-unknown-unknown/wasm/demesne_runtime_wasm.wasm"
node -e '
const fs = require("fs");
const dir = process.argv[1];
const b64 = fs.readFileSync(dir + "/demesne_runtime_wasm_bg.wasm").toString("base64");
fs.writeFileSync(dir + "/bytes.js", "// Code generated by scripts/build-runtime-wasm.sh. DO NOT EDIT.\nexport const BYTES = \"" + b64 + "\";\n");
fs.writeFileSync(dir + "/bytes.d.ts", "export declare const BYTES: string;\n");
' "$OUT"
